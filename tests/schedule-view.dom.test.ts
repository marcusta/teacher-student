import { test, expect } from 'bun:test';
import { di, Router } from '@basics/core/client/core';
import { AuthService } from '@basics/core/client/auth';
import { Hono } from 'hono';
import { SessionStore, createAuth } from '@basics/core/server/auth';
import { mount } from '@basics/core/server/mount';
import { scheduleFixture } from '../server/testing/schedule';
import { createStablesApi } from '../server/api/stables.api';
import { createStableActivitiesApi } from '../server/api/stable-activities.api';
import { createScheduleTemplatesApi } from '../server/api/schedule-templates.api';
import { ScheduleComponent } from '../web/schedule/schedule.component';
import { ScheduleService } from '../web/schedule/schedule.service';
import { addDays } from '../shared/schedule-calendar';

test('the real weekly view renders aligned tables and preserves horse and mine filters', async () => {
    const c = await scheduleFixture(), sessions = new SessionStore(':memory:');
    await sessions.init();
    const realFetch = globalThis.fetch;
    let view: ScheduleComponent | undefined;
    try {
        const app = new Hono();
        app.use(createAuth(sessions, id => c.userService.findById(id)));
        mount(app, '/api', createStablesApi(c.stableService));
        mount(app, '/api', createStableActivitiesApi(c.scheduleService, c.scheduleTrainingService));
        mount(app, '/api', createScheduleTemplatesApi(c.scheduleTemplateService));
        const cookie = `session=${await sessions.create(c.admin.id)}`;
        globalThis.fetch = (async (url, init) => app.fetch(new Request(new URL(String(url), 'http://localhost'), { ...init, headers: { ...Object.fromEntries(new Headers(init?.headers)), cookie } }))) as typeof fetch;
        const now = new Date().toISOString().slice(0, 10);
        await c.scheduleService.create(c.admin.id, c.stable.id, { requestId: 'view', typeId: c.type('care'), horseId: c.horse.id, title: 'Markservice', date: now, assigneeIds: [c.admin.id] });
        di.reset();
        di.get(AuthService).currentUser.set({ id: c.admin.id, username: c.admin.email });
        di.get(Router).navigate('/veckoschema/' + c.stable.id, true);
        document.body.innerHTML = '<div id="schedule-test"></div>';
        view = new ScheduleComponent();
        view.mount(document.getElementById('schedule-test')!);
        for (let i = 0; i < 100 && document.querySelectorAll('.schedule-table').length !== 2; i++) await new Promise(r => setTimeout(r, 10));
        expect(document.querySelectorAll('.schedule-table')).toHaveLength(2);
        expect(document.querySelectorAll('[data-horse-lane]')).toHaveLength(1);
        const add = document.querySelector<HTMLButtonElement>(`[data-new-horse="${c.horse.id}"][data-new-day="2"]`)!;
        add.click();
        expect(document.querySelector<HTMLSelectElement>('dialog [name="horseId"]')?.value).toBe(c.horse.id);
        expect(document.querySelector<HTMLInputElement>('dialog [name="date"]')?.value).toBe(addDays(di.get(ScheduleService).week.get()!.startDate, 2));
        expect(document.querySelector('dialog [name="performedWall"]')).toBeNull();
        document.querySelector<HTMLButtonElement>('dialog [data-action="close"]')!.click();
        for (const action of ['all', 'stable', 'horses', 'horse:' + c.horse.id]) expect(document.querySelector(`[data-scope="${action}"]`)).not.toBeNull();
        (document.querySelector('[data-scope="horses"]') as HTMLButtonElement).click();
        (document.querySelector('[data-action="mine"]') as HTMLButtonElement).click();
        expect(document.querySelector('[data-action="mine"]')?.getAttribute('aria-pressed')).toBe('true');
        for (let i = 0; i < 100 && di.get(ScheduleService).loading.get(); i++) await new Promise(r => setTimeout(r, 10));
        expect(document.querySelectorAll('.schedule-stable-table')).toHaveLength(0);
        expect(document.querySelector('[data-horse-lane]')?.textContent).toContain('Markservice');
        view.destroy();
        document.getElementById('schedule-test')!.replaceChildren();
        view = new ScheduleComponent();
        view.mount(document.getElementById('schedule-test')!);
        for (let i = 0; i < 100 && document.querySelector('[data-action="mine"]')?.getAttribute('aria-pressed') !== 'true'; i++) await new Promise(r => setTimeout(r, 10));
        expect(document.querySelector('[data-scope="horses"]')?.getAttribute('aria-pressed')).toBe('true');
        expect(document.querySelector('[data-action="mine"]')?.getAttribute('aria-pressed')).toBe('true');
        for (let i = 0; i < 100 && di.get(ScheduleService).loading.get(); i++) await new Promise(r => setTimeout(r, 10));
        await c.stableService.setMember(c.admin.id, c.stable.id, c.member.id, 'admin', false);
        await c.stableService.setMember(c.member.id, c.stable.id, c.admin.id, 'member', true);
        await di.get(ScheduleService).loadWeek(c.stable.id, di.get(ScheduleService).week.get()!.startDate);
        expect(di.get(ScheduleService).week.get()).toBeNull();
        expect(di.get(ScheduleService).detail.get()).toBeNull();
        for (let i = 0; i < 100 && document.querySelector('[data-horse-lane]'); i++) await new Promise(r => setTimeout(r, 10));
        expect(document.querySelector('[data-horse-lane]') === null).toBe(true);
    } finally {
        view?.destroy(); globalThis.fetch = realFetch; document.body.innerHTML = '';
        await sessions.close(); await c.db.destroy();
    }
});
